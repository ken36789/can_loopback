/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_FDCAN1_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */
  FDCAN_FilterTypeDef filter = {0};
  filter.IdType = FDCAN_STANDARD_ID;
  filter.FilterIndex = 0;
  filter.FilterType = FDCAN_FILTER_MASK;
  filter.FilterConfig = FDCAN_FILTER_TO_RXFIFO0;
  filter.FilterID1 = 0x000;
  filter.FilterID2 = 0x000;          // mask 全 0 = 全部接收
  HAL_FDCAN_ConfigFilter(&hfdcan1, &filter);
  HAL_FDCAN_ActivateNotification(&hfdcan1, FDCAN_IT_RX_FIFO0_NEW_MESSAGE, 0);
  HAL_FDCAN_Start(&hfdcan1);

  txHeader.Identifier = 0x123;
  txHeader.IdType = FDCAN_STANDARD_ID;
  txHeader.TxFrameType = FDCAN_DATA_FRAME;
  txHeader.DataLength = FDCAN_DLC_BYTES_8;
  txHeader.ErrorStateIndicator = FDCAN_ESI_ACTIVE;
  txHeader.BitRateSwitch = FDCAN_BRS_OFF;
  txHeader.FDFormat = FDCAN_CLASSIC_CAN;
  txHeader.TxEventFifoControl = FDCAN_NO_TX_EVENTS;
  txHeader.MessageMarker = 0;
  printf("CAN loopback start\r\n");

  int32_t lcdStatus = CAN_Display_Init();   // 初始化螢幕並畫出版面
  if (lcdStatus != 0)
    printf("LCD init failed (BSP error %ld)\r\n", lcdStatus);
  else
    printf("LCD ready\r\n");
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    static uint32_t lastTx = 0;
    static uint8_t counter = 0;
    if (HAL_GetTick() - lastTx >= 1000) {        // 每秒發一包
      lastTx = HAL_GetTick();
      for (int i = 0; i < 8; i++) txData[i] = counter + i;
      counter++;
      if (HAL_FDCAN_AddMessageToTxFifoQ(&hfdcan1, &txHeader, txData) == HAL_OK) {
        txCount++;
        printf("TX id=0x%03lX\r\n", txHeader.Identifier);
        CAN_Display_ShowTx(txHeader.Identifier, txData, 8, txCount, 1);
      } else {
        printf("TX fail, free=%lu, PSR=0x%08lX\r\n",
               HAL_FDCAN_GetTxFifoFreeLevel(&hfdcan1), hfdcan1.Instance->PSR);
        CAN_Display_ShowTx(txHeader.Identifier, txData, 8, txCount, 0);
      }
    }
    if (rxFlag) {
      // 先把中斷收到的資料複製出來，避免印到一半被下一包蓋掉
      FDCAN_RxHeaderTypeDef hdr;
      uint8_t data[8];
      __disable_irq();
      hdr = rxHeader;
      memcpy(data, rxData, sizeof(data));
      rxFlag = 0;
      __enable_irq();

      uint32_t len = (hdr.DataLength > 8U) ? 8U : hdr.DataLength;  // Classic CAN: DLC = 位元組數
      rxCount++;
      printf("RX id=0x%03lX data:", hdr.Identifier);
      for (uint32_t i = 0; i < len; i++) printf(" %02X", data[i]);
      printf("\r\n");
      CAN_Display_ShowRx(hdr.Identifier, data, len, rxCount);
    }
  }
  /* USER CODE END 3 */
}

